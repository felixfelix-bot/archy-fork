#!/usr/bin/env bash
# Rehearse the UPGRADE path: a node already running the OLD daemon with an
# OLD-shaped config gets re-pointed at the new config and must re-peer.
#
# ## Why this is a separate test from the smoke test
#
# `fips-live-smoke.sh` boots two fresh daemons on the new config. It proves the
# config is valid. It does NOT prove the thing the bump was actually for: that a
# node which has been running all along — with a `node.discovery.*` config that
# v0.5.0 renamed — still comes back to the mesh once the app rewrites its
# config. That is the scenario `VERIFIED_UPSTREAM_VERSION` exists to cap, and it
# is the one an operator will actually hit.
#
# The test is deliberately conservative about what it can claim: see the
# LIMITS note at the bottom of the output.
#
# ## Usage
#
#   sudo scripts/fips-upgrade-rehearsal.sh [--keep]
#
# Uses the host's installed daemon binary only (no package install, no dpkg, no
# touching the real node's config). The old daemon's identity is preserved
# across the rewrite, which is what makes re-peering meaningful.
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="${FIPS_UPGRADE_WORK:-$REPO/image-recipe/build/fips-upgrade}"
KEEP=0
[ "${1:-}" = "--keep" ] && KEEP=1

NS_A=fips-upgrade-a
NS_B=fips-upgrade-b
FIPS_BIN="${FIPS_BIN:-/usr/bin/fips}"
CTL_BIN="${CTL_BIN:-/usr/bin/fipsctl}"

FAILED=0
pass() { echo "OK:   $*"; }
fail() { echo "FAIL: $*" >&2; FAILED=1; }

cleanup() {
    if [ "$KEEP" = "1" ]; then echo "kept: $WORK"; return; fi
    for ns in "$NS_A" "$NS_B"; do
        ip netns pids "$ns" 2>/dev/null | xargs -r kill 2>/dev/null
        ip netns del "$ns" 2>/dev/null
    done
}
trap cleanup EXIT

[ "$(id -u)" = "0" ] || { echo "FAIL: must run as root" >&2; exit 1; }

# The OLD-shaped config: exactly what archipelago rendered BEFORE this bump.
# Taken from the v0.4.1 fixture's paths, including the three phantom keys, so
# the starting state is the real pre-bump state rather than an approximation.
OLD_CONFIG_HEADER='# Generated by archipelago (PRE-BUMP v0.4.1 shape) - do not edit by hand.'
read -r -d '' OLD_CONFIG_BODY <<'YAML' || true
node:
  identity:
    persistent: true
  discovery:
    timeout_secs: 5
    retry_interval_secs: 2
    max_attempts: 3
    lan:
      enabled: true
  retry:
    base_interval_secs: 1
    max_backoff_secs: 30
    max_retries: 30
tun:
  enabled: true
  name: fips0
  mtu: 1280
dns:
  enabled: true
  bind_addr: 127.0.0.1
transports:
  udp:
    bind_addr: 0.0.0.0:2121
  tcp:
    bind_addr: 0.0.0.0:8443
peers: []
YAML

# The NEW config is the product's own rendering.
NEW_RENDERED="$REPO/tests/fixtures/fips/archipelago-rendered.yaml"
[ -f "$NEW_RENDERED" ] || { echo "FAIL: missing $NEW_RENDERED" >&2; exit 1; }

echo "daemon: $($FIPS_BIN --version | head -1)"
echo
echo "Scenario: both nodes start on the PRE-BUMP config (node.discovery.*),"
echo "then both are rewritten to the POST-BUMP config (node.lookup.* +"
echo "node.rendezvous.*) with the SAME identity, and must re-peer."
echo

rm -rf "$WORK"; mkdir -p "$WORK/a" "$WORK/b"

# ── Topology (same shape as the smoke test) ──────────────────────────────
for ns in "$NS_A" "$NS_B"; do ip netns del "$ns" 2>/dev/null || true; done
ip netns add "$NS_A" || { echo "FAIL: netns $NS_A" >&2; exit 1; }
ip netns add "$NS_B" || { echo "FAIL: netns $NS_B" >&2; exit 1; }
ip link add veth-a type veth peer name veth-b || { echo "FAIL: veth" >&2; exit 1; }
ip link set veth-a netns "$NS_A"; ip link set veth-b netns "$NS_B"
ip -n "$NS_A" addr add 10.214.0.1/24 dev veth-a; ip -n "$NS_A" link set veth-a up
ip -n "$NS_B" addr add 10.214.0.2/24 dev veth-b; ip -n "$NS_B" link set veth-b up
ip -n "$NS_A" link set lo up; ip -n "$NS_B" link set lo up
ip netns exec "$NS_A" ip tuntap add dev fips0 mode tun 2>/dev/null || true
ip netns exec "$NS_B" ip tuntap add dev fips0 mode tun 2>/dev/null || true

# Identity is generated ONCE and preserved across the config rewrite. Without
# that, "re-peered" would be indistinguishable from "two brand-new nodes met".
for n in a b; do
    "$CTL_BIN" keygen --dir "$WORK/$n" --force >/dev/null 2>&1 \
        || { echo "FAIL: keygen $n" >&2; exit 1; }
done

mk_old() { # mk_old <node>  — pre-bump config + this node's identity
    local n="$1" nsec; nsec="$(sed -n '1p' "$WORK/$n/fips.key")"
    { echo "$OLD_CONFIG_HEADER"
      # Insert an explicit nsec under the old identity block.
      sed "s|^  identity:$|  identity:\n    nsec: \"$nsec\"|" <<<"$OLD_CONFIG_BODY"
    } > "$WORK/$n/fips.yaml"
}
mk_new() { # mk_new <node>  — post-bump config + the SAME identity
    local n="$1" nsec; nsec="$(sed -n '1p' "$WORK/$n/fips.key")"
    awk -v nsec="$nsec" '
        /^  identity:$/ && !done { print "  identity:"; print "    nsec: \"" nsec "\""; done=1; next }
        done && !left && /^    persistent:/ { next }
        /^  lookup:$/ { left=1 }
        { print }
    ' "$NEW_RENDERED" > "$WORK/$n/fips.yaml"
}

# Randomised/scoped output paths so this cannot collide with the smoke test.
boot() { # boot <node> <logname>
    local n="$1" tag="$2"
    ip netns exec "fips-upgrade-$n" unshare --mount --propagation private \
        sh -c "mount -t tmpfs tmpfs /run; mkdir -p /run/fips; mount -t tmpfs tmpfs -o size=1m /etc/fips; exec \"\$0\" --config \"\$1\"" \
        "$FIPS_BIN" "$WORK/$n/fips.yaml" >"$WORK/$n/$tag.log" 2>&1 &
    echo $! > "$WORK/$n/daemon.pid"
}
stop() { # stop <node>
    local pid; pid="$(cat "$WORK/$1/daemon.pid" 2>/dev/null)"
    [ -n "$pid" ] && kill "$pid" 2>/dev/null
    # A namespace-bound daemon ignores a plain kill from outside its ns in some
    # kernels; escalate via the ns pid list so the port is actually released.
    ip netns pids "fips-upgrade-$1" 2>/dev/null | xargs -r kill 2>/dev/null
    sleep 2
}
ctl_ns() { # ctl_ns <node> <args...>
    local n="$1"; shift
    local pid; pid="$(cat "$WORK/$n/daemon.pid")"
    nsenter --target "$pid" --net --mount --pid --uts --ipc "$CTL_BIN" "$@" 2>&1
}
peers() { # peers <node> — count authenticated peers
    ctl_ns "$1" show peers 2>/dev/null \
        | sed -n 's/.*"authenticated_at_ms":[[:space:]]*\([0-9]*\).*/\1/p' | wc -l
}
wait_peers() { # wait_peers <node> <want> <secs>
    local n="$1" want="$2" deadline=$(( SECONDS + $3 ))
    while [ "$SECONDS" -lt "$deadline" ]; do
        [ "$(peers "$n")" -ge "$want" ] && return 0
        sleep 2
    done
    return 1
}

NPUB_A="$(tr -d '[:space:]' < "$WORK/a/fips.pub")"
NPUB_B="$(tr -d '[:space:]' < "$WORK/b/fips.pub")"

# ── Phase 1: peer on the OLD (pre-bump) config ───────────────────────────
echo "── Phase 1: both nodes on the PRE-BUMP config (node.discovery.*) ──"
mk_old a; mk_old b
boot a old; boot b old

# Confirm the old config is what we think it is before drawing conclusions.
if grep -q "discovery:" "$WORK/a/fips.yaml"; then
    pass "old config really uses node.discovery.* (the pre-bump shape)"
else
    fail "old config does not contain discovery: — the starting state is wrong"
fi

if wait_peers a 1 45 && wait_peers b 1 45; then
    pass "pre-bump config peers (a=$(peers a) b=$(peers b))"
else
    fail "pre-bump config did NOT peer (a=$(peers a) b=$(peers b))"
    tail -12 "$WORK/a/old.log" >&2
fi

# Record the peer identity so Phase 3 can prove it is the SAME relationship.
OLD_SEEN_B="$(ctl_ns a show peers 2>/dev/null | grep -c "$NPUB_B")"

# ── Phase 2: rewrite the config to the post-bump shape, SAME identity ────
echo
echo "── Phase 2: rewrite both configs to the POST-BUMP shape ──"
stop a; stop b
mk_new a; mk_new b

for n in a b; do
    if grep -q "discovery:" "$WORK/$n/fips.yaml"; then
        fail "node $n new config still carries node.discovery.*"
    fi
    if grep -q "lookup:" "$WORK/$n/fips.yaml" && grep -q "rendezvous:" "$WORK/$n/fips.yaml"; then
        pass "node $n new config uses node.lookup.* + node.rendezvous.*"
    else
        fail "node $n new config is missing the new key paths"
    fi
    # The identity MUST be unchanged, or re-peering proves nothing.
    if [ "$(tr -d '[:space:]' < "$WORK/$n/fips.pub")" = "$([ "$n" = a ] && echo "$NPUB_A" || echo "$NPUB_B")" ]; then
        pass "node $n identity preserved across the rewrite"
    else
        fail "node $n identity CHANGED — re-peering would be meaningless"
    fi
done

# ── Phase 3: the daemon must come up on the NEW config and RE-peer ───────
echo
echo "── Phase 3: restart on the new config; must be ACCEPTED and re-peer ──"
boot a new; boot b new

# Acceptance first: a rejected config is the loud failure, and distinguishing it
# from "started but idle" is the whole reason we check the log.
for n in a b; do
    if grep -qi "failed to load configuration\|did not find expected key\|refusing to start" "$WORK/$n/new.log"; then
        fail "node $n REJECTED the post-bump config"
        grep -i "failed to load configuration\|refusing to start" "$WORK/$n/new.log" | head -3 >&2
    else
        pass "node $n accepted the post-bump config (no parse/validate error)"
    fi
done

if wait_peers a 1 60 && wait_peers b 1 60; then
    pass "re-peered after the config rewrite (a=$(peers a) b=$(peers b))"
    if [ "$OLD_SEEN_B" -gt 0 ]; then
        pass "same peer relationship as before the rewrite (node b present both times)"
    fi
else
    fail "did NOT re-peer after the config rewrite (a=$(peers a) b=$(peers b))"
    echo "── node a new.log (tail) ──" >&2; tail -20 "$WORK/a/new.log" >&2
    echo "── node b new.log (tail) ──" >&2; tail -20 "$WORK/b/new.log" >&2
fi

# ── LIMITS ───────────────────────────────────────────────────────────────
cat <<'LIMITS'

LIMITS — what this rehearsal does NOT prove:
  * The daemon binary is the INSTALLED one (0.5.3). This rehearses the CONFIG
    migration and the daemon's acceptance of it, not a .deb upgrade from 0.4.1,
    which needs the v0.4.1 package and a dpkg transaction.
  * It does not exercise archipelago's own `sudo install` of fips.yaml, nor the
    unit-file swaps around it.
  * It is not an upgrade of a long-running node with accumulated state; both
    nodes are started fresh on the old config, then rewritten.
LIMITS

echo
if [ "$FAILED" -ne 0 ]; then
    echo "RESULT: FAIL — the upgrade path is not proven"
    exit 1
fi
echo "RESULT: PASS — a pre-bump-config node accepts the post-bump config and re-peers"
